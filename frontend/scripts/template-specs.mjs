// The starter templates as plain descriptions: shapes by library key, a position on a grid
// (COL x ROW), lines between them by id. scripts/build-templates.mjs turns them into Oqiva
// documents with the engine's own factories.

export const COL = 260
export const ROW = 160

// n(id, preset, label, column, row, options): a library shape at a grid cell.
const n = (id, preset, label, col, row, o = {}) => ({ id, preset, label, col, row, ...o })
// e(from, to, label, options): a line between two shapes.
const e = (from, to, label = null, o = {}) => ({ from, to, label, ...o })
// note(id, text, color, x, y), text(id, text, x, y, size), frame(name, x, y, w, h)
const note = (id, text, color, x, y, o = {}) => ({ id, text, color, x, y, ...o })
const text = (id, content, x, y, size = "m") => ({ id, text: content, x, y, size })
const frame = (name, x, y, w, h) => ({ name, x, y, w, h })

