const SRC = "node_modules/lucide-static/icons"
const out = {}
for (const [name, tags] of Object.entries(NAMES)) {
	const svg = fs.readFileSync(`${SRC}/${name}.svg`, "utf8")
	const shapes = []
	for (const match of svg.matchAll(
		/<(path|rect|circle|line|polyline|polygon|ellipse)\b([^>]*?)\/>/g,
	)) {
		const attrs = {}
		for (const a of match[2].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) attrs[a[1]] = a[2]
		shapes.push([match[1], attrs])
	}
	if (!shapes.length) throw new Error(`no shapes in ${name}`)
	out[name] = { label: name.replace(/-/g, " "), tags, shapes }
}
const body = `// Generated by scripts/build-icons.mjs from lucide-static (ISC licence, https://lucide.dev).
// Do not edit by hand.
export const ICON_DATA = ${JSON.stringify(out, null, "\t")}
`
fs.writeFileSync("src/engine/model/iconData.js", body)
console.log(`wrote ${Object.keys(out).length} icons`)
